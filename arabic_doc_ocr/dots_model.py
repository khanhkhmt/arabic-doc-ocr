"""dots.mocr (layout + printed text), run the same way as the authors' code (github.com/studio-dots-ai/dots.ocr,
commit 36d7248; their utils are vendored unchanged in `_vendor/dots_ocr`):

    image ─► fetch_image ─► layout prompt ─► chat template + process_vision_info + processor + generate
          ─► post_process_output (JSON → boxes on the input image; broken JSON → their OutputCleaner)

Changes needed to run on GPUs without FlashAttention / bf16 (e.g. T4); none changes the model's arithmetic:
- vision encoder: sdpa instead of flash_attention_2, attention computed per image without the N×N mask (same maths,
  memory-efficient kernel), run in float32; language model in fp16 (bf16 on Ampere and newer);
- the image embeddings are merged into the input sequence by their own `prepare_inputs_embeds` and the text is
  generated by the Qwen2 language model (their `generate` only injects the image when `cache_position[0] == 0`,
  which newer transformers no longer pass → the model would not see the image);
- generation stops early when the output loops (the same output their cleaner would produce, minus the wasted time).
"""

from __future__ import annotations

import functools
import importlib.machinery
import json
import re
import sys
import tempfile
import types
from pathlib import Path

from PIL import Image

from . import config

_VENDOR = str(Path(__file__).resolve().parent / "_vendor")


def _dots_utils():
    if _VENDOR not in sys.path:
        sys.path.insert(0, _VENDOR)
    from dots_ocr.utils import image_utils, layout_utils, prompts

    return prompts, image_utils, layout_utils


def pick_dtype(torch, device: str):
    """bf16 on Ampere and newer, fp16 on older GPUs (T4: is_bf16_supported() lies, check the compute capability)."""
    if not device.startswith("cuda"):
        return torch.float32
    return torch.bfloat16 if torch.cuda.get_device_capability(device)[0] >= 8 else torch.float16


def _local_dir(model_id: str, alias: str) -> str:
    """Their remote code uses the folder name as a Python module name, so 'dots.mocr' fails to import: download to the
    HF cache and point a folder without dots at it (symlink)."""
    from huggingface_hub import snapshot_download

    src = Path(model_id) if Path(model_id).is_dir() else Path(snapshot_download(model_id))
    link = Path(tempfile.gettempdir()) / "arabic_doc_ocr_models" / alias
    link.parent.mkdir(parents=True, exist_ok=True)
    if link.is_symlink() or link.exists():
        if link.resolve() == src.resolve():
            return str(link)
        link.unlink()
    link.symlink_to(src, target_is_directory=True)
    return str(link)


# --- patches for the vision encoder ---------------------------------------------------------------------------------

def _install_flash_attn_stub() -> None:
    """modeling_dots_vision.py imports flash_attn at the top; the stub is never called (sdpa is forced below)."""
    try:
        import flash_attn  # noqa: F401
        return
    except ImportError:
        pass
    mod = types.ModuleType("flash_attn")
    mod.__spec__ = importlib.machinery.ModuleSpec("flash_attn", None)

    def _missing(*a, **k):
        raise RuntimeError("flash_attn is not installed (the vision encoder should have been switched to sdpa)")

    mod.flash_attn_varlen_func = _missing
    mod.flash_attn_func = _missing
    sys.modules["flash_attn"] = mod


def _per_image_sdpa_forward(self, hidden_states, cu_seqlens, rotary_pos_emb=None):
    """Replaces VisionSdpaAttention.forward: attention per image (cu_seqlens segment), no mask — identical maths to
    the masked full attention, but PyTorch can use a memory-efficient kernel (the mask needs ~5 GB per layer)."""
    import torch
    import torch.nn.functional as F

    apply_rope = sys.modules[type(self).__module__].apply_rotary_pos_emb_vision
    n = hidden_states.shape[0]
    q, k, v = self.qkv(hidden_states).reshape(n, 3, self.num_heads, -1).permute(1, 0, 2, 3).unbind(0)
    q = apply_rope(q.unsqueeze(0), rotary_pos_emb).squeeze(0)
    k = apply_rope(k.unsqueeze(0), rotary_pos_emb).squeeze(0)
    outs = []
    bounds = cu_seqlens.tolist()
    for a, b in zip(bounds[:-1], bounds[1:]):
        qi, ki, vi = (t[a:b].transpose(0, 1).unsqueeze(0) for t in (q, k, v))
        outs.append(F.scaled_dot_product_attention(qi, ki, vi, dropout_p=0.0).squeeze(0).transpose(0, 1))
    return self.proj(torch.cat(outs, dim=0).reshape(n, -1))


def _patch_before_load(cfg) -> None:
    _install_flash_attn_stub()
    vc = getattr(cfg, "vision_config", None)
    if vc is not None:
        if isinstance(vc, dict):
            vc["attn_implementation"] = "sdpa"
        else:
            vc.attn_implementation = "sdpa"


def _patch_after_load(model, vision_dtype) -> None:
    tower = model.vision_tower
    tower.to(vision_dtype)
    n = 0
    for m in tower.modules():
        if type(m).__name__ == "VisionSdpaAttention":
            m.forward = types.MethodType(_per_image_sdpa_forward, m)
            n += 1
    if n == 0:
        raise RuntimeError("dots vision patch: no VisionSdpaAttention layer found — the model code has changed")
    orig = tower.forward

    @functools.wraps(orig)
    def forward(hidden_states, grid_thw, bf16=True):  # ignore the original's cast to bf16
        return orig(hidden_states.to(vision_dtype), grid_thw, bf16=False)

    tower.forward = forward


# --- loop detection -------------------------------------------------------------------------------------------------

class _TokenLoopStop:
    """The tail of the output is a short span (≤ max_period tokens) repeated back to back over ≥ min_span tokens."""

    def __init__(self, start: int, max_period: int, min_span: int, every: int = 16):
        self.start, self.max_period, self.min_span, self.every = start, max_period, min_span, every
        self.stopped = False
        self.calls = 0

    def __call__(self, input_ids) -> bool:
        self.calls += 1
        gen = input_ids[0, self.start:]
        if self.stopped or self.calls % self.every or gen.shape[0] < self.min_span:
            return self.stopped
        t = gen[-max(self.min_span, 2 * self.max_period):].tolist()
        for period in range(1, self.max_period + 1):
            reps = -(-self.min_span // period)
            span = period * reps
            if span > len(t):
                break
            seg = t[-span:]
            if seg == seg[:period] * reps:
                self.stopped = True
                break
        return self.stopped


_CELL = re.compile(r'"category":\s*"([^"]+)"\s*,\s*"text":\s*"((?:[^"\\\\]|\\\\.)*)"')


def layout_loop(text: str, min_repeats: int = 25, min_chars: int = 6) -> bool:
    """The layout JSON ends with ONE (category, text) pair repeated ≥ min_repeats times (boxes may differ). Their
    cleaner removes such duplicates anyway, so stopping early gives the same result, only faster."""
    cells = _CELL.findall(text)
    if len(cells) < min_repeats:
        return False
    last = cells[-1]
    if len(last[1]) < min_chars:
        return False
    n = 0
    for c in reversed(cells):
        if c != last:
            break
        n += 1
    return n >= min_repeats


class _LayoutLoopStop:
    def __init__(self, tokenizer, start: int, every: int = 64, tail_tokens: int = 6000):
        self.tok, self.start, self.every, self.tail = tokenizer, start, every, tail_tokens
        self.calls = 0
        self.stopped = False

    def __call__(self, input_ids) -> bool:
        self.calls += 1
        if not self.stopped and self.calls % self.every == 0 and input_ids.shape[1] - self.start > 200:
            gen = input_ids[0, max(self.start, input_ids.shape[1] - self.tail):]
            self.stopped = layout_loop(self.tok.decode(gen, skip_special_tokens=True))
        return self.stopped


# --- model ----------------------------------------------------------------------------------------------------------

class DotsLayout:
    """dots.mocr on one device. parse(image) → {"blocks": [{category, bbox, text}], "raw": …, info…}."""

    def __init__(self, device: str = "cuda:0", model_id: str = config.DOTS_MODEL):
        self.device, self.model_id = device, model_id
        self.model = self.processor = None

    def load(self) -> "DotsLayout":
        import torch
        import transformers
        from qwen_vl_utils import process_vision_info
        from transformers import Qwen2ForCausalLM

        self.torch, self._process_vision_info = torch, process_vision_info
        path = _local_dir(self.model_id, "DotsMOCR")
        cfg = transformers.AutoConfig.from_pretrained(path, trust_remote_code=True)
        _patch_before_load(cfg)
        major, minor = (int(x) for x in transformers.__version__.split(".")[:2])
        kw = {"dtype" if (major, minor) >= (4, 56) else "torch_dtype": pick_dtype(torch, self.device)}
        self.model = transformers.AutoModelForCausalLM.from_pretrained(
            path, config=cfg, attn_implementation="sdpa", device_map={"": self.device}, trust_remote_code=True, **kw)
        _patch_after_load(self.model, torch.float32)
        self.model.eval()
        # generate with the plain Qwen2 path (inputs_embeds already contain the image)
        self.model.prepare_inputs_for_generation = types.MethodType(
            Qwen2ForCausalLM.prepare_inputs_for_generation, self.model)
        self.model.forward = types.MethodType(Qwen2ForCausalLM.forward, self.model)
        self.processor = transformers.AutoProcessor.from_pretrained(path, trust_remote_code=True, use_fast=True)
        return self

    def to(self, device: str) -> None:
        """Move between GPU and CPU RAM (single-GPU machines: only one model on the GPU at a time)."""
        self.model.to(device)

    def _generate(self, image: Image.Image, prompt: str) -> tuple[str, dict]:
        torch = self.torch
        from transformers import StoppingCriteria, StoppingCriteriaList

        messages = [{"role": "user", "content": [{"type": "image", "image": image}, {"type": "text", "text": prompt}]}]
        text = self.processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
        image_inputs, video_inputs = self._process_vision_info(messages)
        inputs = self.processor(text=[text], images=image_inputs, videos=video_inputs, padding=True,
                                return_tensors="pt")
        inputs.pop("mm_token_type_ids", None)  # newer transformers add this key; the dots model does not take it
        inputs = inputs.to(self.model.device)
        ids = inputs["input_ids"]
        start = ids.shape[1]
        with torch.inference_mode():
            emb = self.model.prepare_inputs_embeds(ids, inputs["pixel_values"], inputs["image_grid_thw"],
                                                   ids == self.model.config.image_token_id)
        n_img = int((ids == self.model.config.image_token_id).sum())
        max_new = min(config.DOTS_MAX_NEW_TOKENS, config.DOTS_TOKENS_PER_IMAGE_TOKEN * n_img + 512)
        loop = _TokenLoopStop(start, config.DOTS_LOOP_MAX_PERIOD, config.DOTS_LOOP_MIN_SPAN)
        layout = _LayoutLoopStop(getattr(self.processor, "tokenizer", self.processor), start)

        class _Stop(StoppingCriteria):
            def __call__(self, input_ids, scores, **kw):
                return torch.tensor([loop(input_ids) | layout(input_ids)], device=input_ids.device)

        with torch.inference_mode():
            out = self.model.generate(input_ids=ids, inputs_embeds=emb, attention_mask=inputs["attention_mask"],
                                      max_new_tokens=max_new, stopping_criteria=StoppingCriteriaList([_Stop()]))
        if out.shape[1] >= start and torch.equal(out[:, :start].to(ids.device), ids):
            new = out[0, start:]
        else:  # some transformers versions return only the new tokens
            new = out[0]
        response = self.processor.batch_decode([new], skip_special_tokens=True, clean_up_tokenization_spaces=False)[0]
        n_new = int(new.shape[0])
        info = {"new_tokens": n_new, "hit_max_tokens": n_new >= max_new, "max_new_tokens": max_new,
                "stopped_loop": loop.stopped}
        return response, info

    def parse(self, image: Image.Image) -> dict:
        """Layout of one page image → blocks with boxes in `image` coordinates and the text dots read in each."""
        prompts, image_utils, layout_utils = _dots_utils()
        if self.model is None:
            self.load()
        origin = image.convert("RGB")
        img = image_utils.fetch_image(origin, min_pixels=None, max_pixels=None)
        response, info = self._generate(img, prompts.dict_promptmode_to_prompt[config.DOTS_PROMPT])
        cells, filtered = layout_utils.post_process_output(response, config.DOTS_PROMPT, origin, img,
                                                           min_pixels=None, max_pixels=None)
        info["layout"] = "filtered" if filtered else "ok"
        blocks = [] if filtered else [{"category": c.get("category"), "bbox": c.get("bbox"), "text": c.get("text", "")}
                                      for c in cells]
        return {"blocks": blocks, "raw": response if filtered else json.dumps(cells, ensure_ascii=False), **info}

    def close(self) -> None:
        self.model = None
